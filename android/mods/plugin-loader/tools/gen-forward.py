#!/usr/bin/env python3
"""Generates api/src/forward.rs: Hooks and RenderHooks forwarders over loaded plugins.

Input: the generated trait files (mod_api_generated.rs, native_render_generated.rs) that
Horizon's horizon-mod-api-gen writes to OUT_DIR (see README.md).
Rules mirror docs/native-mods.md: the first Cancel stops, the first Some wins, others call every plugin.
"""
import re, sys

def methods(path, name):
    t = open(path).read()
    i = t.index("pub trait " + name)
    body = t[i:t.index("\n}\n", i)]
    for m in re.finditer(r"^fn (\w+)\((.*?)\)( -> (.*?))? \{", body, re.M):
        yield m.group(1), m.group(2), (m.group(4) or "").strip()

def split_params(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "<(": depth += 1
        elif ch in ">)": depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out

def emit(path, trait, plug, out, render=False):
    for name, params, ret in methods(path, trait):
        if name == "render" and trait == "Hooks":
            continue
        args = split_params(params)[1:]  # drop &self
        names = ", ".join(a.split(":")[0].strip() for a in args)
        sig = ", ".join(["&self"] + args)
        it = "self.render_plugins()" if render else "self.plugins()"
        r = ret.replace(" ", "")
        if ret == "":
            body = f"for p in {it} {{ p.{name}({names}); }}"
            out.append(f"fn {name}({sig}) {{ {body} }}")
        elif r == "Flow":
            body = f"for p in {it} {{ if p.{name}({names}) == Flow::Cancel {{ return Flow::Cancel; }} }} Flow::Continue"
            out.append(f"fn {name}({sig}) -> Flow {{ {body} }}")
        elif r.startswith("Option<"):
            body = f"for p in {it} {{ if let Some(v) = p.{name}({names}) {{ return Some(v); }} }} None"
            out.append(f"fn {name}({sig}) -> {ret} {{ {body} }}")
        else:
            raise SystemExit(f"unsupported return type for {name}: {ret}")

hooks, render, dest = sys.argv[1:4]
out = ["// @generated by tools/gen-forward.py; do not edit.", "use super::Loader;", "use horizon_client::gfx::native_render::HandDrawnEvent;", "use horizon_client::mod_api::*;", "",
       "impl Hooks for Loader {",
       "fn render(&self) -> Option<&dyn RenderHooks> { Some(self) }"]
emit(hooks, "Hooks", "p", out)
out += ["}", "", "impl RenderHooks for Loader {"]
emit(render, "RenderHooks", "p", out, render=True)
out += ["}", ""]
open(dest, "w").write("\n".join(out))
